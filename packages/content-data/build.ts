import {
  parseArticle,
  parseDecks,
  parseEvents,
  parseRotations,
  parseSets,
  sortArticles,
  validateCatalog,
} from "@prize-map/content";

const sourceDirectory = `${import.meta.dir}/posts`;
const dataDirectory = `${import.meta.dir}/data`;
const outputDirectory = `${import.meta.dir}/dist`;

async function readData<Item>(
  file: string,
  parse: (source: string, sourcePath: string) => Item[],
): Promise<Item[]> {
  const sourcePath = `${dataDirectory}/${file}`;
  return parse(await Bun.file(sourcePath).text(), sourcePath);
}

async function build(): Promise<void> {
  const files = await Array.fromAsync(
    new Bun.Glob("*.md").scan({ cwd: sourceDirectory, onlyFiles: true }),
  );
  const articles = await Promise.all(
    files.map(async (file) => {
      const sourcePath = `${sourceDirectory}/${file}`;
      return parseArticle(await Bun.file(sourcePath).text(), sourcePath)
        .article;
    }),
  );

  const [decks, sets, rotations, events] = await Promise.all([
    readData("decks.yaml", parseDecks),
    readData("sets.yaml", parseSets),
    readData("rotations.yaml", parseRotations),
    readData("events.yaml", parseEvents),
  ]);

  // Drafts are validated too, so a hidden post can't break when it is published.
  const errors = validateCatalog({
    posts: articles,
    decks,
    sets,
    rotations,
    events,
  });
  if (errors.length > 0) {
    throw new Error(`Content references are broken:\n- ${errors.join("\n- ")}`);
  }

  const posts = sortArticles(articles.filter((article) => article.visible));
  const catalog = { posts, decks, sets, rotations, events };

  await Bun.$`rm -rf ${outputDirectory}`;
  await Bun.$`mkdir -p ${outputDirectory}`;
  await Bun.write(
    `${outputDirectory}/catalog.json`,
    JSON.stringify(catalog, null, 2),
  );
  await Bun.write(
    `${outputDirectory}/index.js`,
    [
      "// Generated by packages/content-data/build.ts. Do not edit.",
      ...Object.entries(catalog).map(
        ([name, value]) => `export const ${name} = ${JSON.stringify(value)};`,
      ),
      "",
    ].join("\n"),
  );

  console.info(
    `Built ${posts.length} published post${posts.length === 1 ? "" : "s"}, ` +
      `${decks.length} decks, ${sets.length} sets, ${rotations.length} rotations, ${events.length} events.`,
  );
}

await build();
