import { parseArticle, sortArticles } from "@prize-map/content";

const sourceDirectory = `${import.meta.dir}/posts`;
const outputDirectory = `${import.meta.dir}/dist`;

async function build(): Promise<void> {
  const files = await Array.fromAsync(
    new Bun.Glob("*.md").scan({ cwd: sourceDirectory, onlyFiles: true }),
  );
  const articles = await Promise.all(
    files.map(async (file) => {
      const sourcePath = `${sourceDirectory}/${file}`;
      return parseArticle(await Bun.file(sourcePath).text(), sourcePath)
        .article;
    }),
  );

  const visibleArticles = sortArticles(
    articles.filter((article) => article.visible),
  );
  const slugs = new Set<string>();
  for (const article of visibleArticles) {
    if (slugs.has(article.slug)) {
      throw new Error(`Duplicate article slug: ${article.slug}`);
    }
    slugs.add(article.slug);
  }

  await Bun.$`rm -rf ${outputDirectory}`;
  await Bun.$`mkdir -p ${outputDirectory}`;
  await Bun.write(
    `${outputDirectory}/posts.json`,
    JSON.stringify(visibleArticles, null, 2),
  );
  await Bun.write(
    `${outputDirectory}/index.js`,
    `// Generated by packages/content-data/build.ts. Do not edit.\nexport const posts = ${JSON.stringify(visibleArticles)};\n`,
  );

  console.info(
    `Built ${visibleArticles.length} published article${visibleArticles.length === 1 ? "" : "s"}.`,
  );
}

await build();
